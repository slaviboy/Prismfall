import type { InputAction, MenuDirection } from '../settings/schema';

export type InputDevice = 'keyboard' | 'gamepad' | 'xr';

/** A device-level control change, before any action mapping. */
export interface RawInputEvent {
  readonly device: InputDevice;
  /** Gamepad slot index (gamepad only). */
  readonly pad: number;
  /** KeyboardEvent.code, "button:<i>" / "axis:<i>:<+|->" (standard mapping) or "xr:<hand>:<control>". */
  readonly control: string;
  readonly down: boolean;
  /** performance.now()-compatible timestamp. */
  readonly time: number;
}

export type InputContext = 'gameplay' | 'menu' | 'capture' | 'none';

export type MenuAction = 'confirm' | 'back' | MenuDirection;

export interface ActionEvent<A extends string = InputAction | MenuAction> {
  readonly action: A;
  readonly down: boolean;
  readonly time: number;
  readonly device: InputDevice;
  /** Auto-repeat event generated by menu navigation (not a physical press). */
  readonly repeat: boolean;
}

export type PadFamily = 'playstation' | 'xbox' | 'generic';

export interface PadInfo {
  readonly index: number;
  readonly id: string;
  readonly name: string;
  readonly family: PadFamily;
  readonly standard: boolean;
  readonly buttons: number;
  readonly axes: number;
  readonly vibration: boolean;
  readonly triggerRumble: boolean;
}
